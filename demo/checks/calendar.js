  check('tomorrow shows its own heading and no figures', c1.includes(long(off(1))) && !/Jobs today/.test(c1));
  check('tomorrow shows the Dentist event from Home', /Dentist/.test(c1) && /3:00 to 4:00 PM · Home/.test(c1), c1);
  check('Today button appears on another day', (await p.locator('#nav [data-action="cal-today"]').count()) === 1);
  await day(off(-2));
  const c2 = await text('#content');
  check('two days ago shows Dumpster 4 drop-off', /Dumpster 4 drop-off/.test(c2), c2);
