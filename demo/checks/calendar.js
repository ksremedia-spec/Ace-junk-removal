  check('next month arrow changes the month', (await text('#content .month .mtitle')) !== title0);
  await p.click('#content [data-action="cal-month"][data-step="-1"]'); await p.waitForTimeout(80);
  await p.click('#content [data-action="open-event"][data-id="e1"]'); await p.waitForTimeout(80);
  const ev = await text('#content');
  check('an event opens a read-only page', /Truck 2 inspection/.test(ev) && /Calendar/.test(ev) && /Alex/.test(ev) && /from 7:00 AM to 7:45 AM/.test(ev), ev);
