  await p.click('.sheet [data-action="close-sheet"]'); await p.waitForTimeout(80);
  await p.click('#nav [data-action="cal-today"]'); await p.waitForTimeout(80);
  check('Today button goes back to today', (await p.locator(`#content [data-date="${off(0)}"].sel`).count()) === 1 && !(await p.locator('#nav [data-action="cal-today"]').count()));
