const { open, done, A, refIn } = require('./harness');
const OUT = require('path').join(__dirname, 'shots') + '/';
let fails = 0; const check = (n, c, x) => { console.log((c ? 'ok   ' : 'FAIL ') + n + (c || x === undefined ? '' : '  [' + String(x).slice(0, 260) + ']')); if (!c) fails++; };
const pad = n => String(n).padStart(2, '0'); const iso = d => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const plus = n => { const d = new Date(); d.setDate(d.getDate() + n); return iso(d); };
const norm = t => (t || '').replace(/[\s ]+/g, ' ');
(async () => {
  const h = await open(); const p = h.page;
  const content = async () => norm(await p.locator('#content').textContent());
  const overlay = async () => norm(await p.locator('#overlay').textContent());
  const setTime = async (sel, v) => { await p.fill(sel, v); await p.dispatchEvent(sel, 'change'); await p.waitForTimeout(90); };
  let c = await content();
  check('Today: Linda 9:00 to 11:00 AM, Pereira just 1:00 PM', /Linda Johnson.*?9:00 to 11:00 AM/.test(c) && /Pereira.*?1:00 PM/.test(c) && !/1:00 to/.test(c), c.slice(0, 500));
  await p.click('[data-action="tab"][data-tab="jobs"]'); await p.waitForTimeout(100);
  await p.click('#content [data-action="open-job"][data-id="j4"]'); await p.waitForTimeout(120);
  c = await content();
  check('a 10:00 start inside 8:00 to 11:00 shows the note', /Overlaps Tom & Sue Keane, Junk removal, 8:00 to 11:00 AM\./.test(c), c.slice(0, 500));
  check('no end time unless set (switch off)', (await p.locator('#content [data-toggle="hasEnd"]').getAttribute('aria-checked')) === 'false' && !(await p.locator('#f-end').count()));
  await setTime('#f-time', '11:00');
  check('11:00 (when the other ends) is not a clash', !/Overlaps/.test(await content()));
  await p.click('#nav [data-action="save-job"]'); await p.waitForTimeout(150);
  check('no question when nothing clashes', !(await p.locator('#overlay .dialog').count()) && (await h.toast()).includes('Job saved.'));
  await p.click('[data-action="tab"][data-tab="today"]'); await p.waitForTimeout(100);
  await p.click('#content [data-action="new-job"]'); await p.waitForTimeout(100);
  await p.click('#overlay [data-action="pick-customer"]'); await p.waitForTimeout(80); await p.click('#overlay [data-action="picker-choose"][data-id="c6"]'); await p.waitForTimeout(80);
  await setTime('#f-date', plus(0)); await setTime('#f-time', '10:00');
  check('a 10:00 start with no end clashes with 9:00 to 11:00', /Overlaps Linda Johnson, Junk removal, 9:00 to 11:00 AM\./.test(await overlay()));
  await p.click('#overlay [data-toggle="hasEnd"]'); await p.waitForTimeout(100);
  check('turning on an end time starts the picker an hour later', (await p.inputValue('#f-end')) === '11:00');
  await setTime('#f-end', '09:30');
  check('an end before the start is flagged', /Ends before it starts\./.test(await overlay()));
  await p.click('#overlay [data-action="save-new-job"]'); await p.waitForTimeout(100);
  check('and Save is refused', (await h.toast()).includes('Ends before it starts.') && /New Job/.test(await overlay()) && !(await p.locator('#overlay .dialog').count()));
  await setTime('#f-end', '14:00');
  check('10:00 to 2:00 PM overlaps Linda and Pereira (and 1 more)', /Overlaps Linda Johnson, Junk removal, 9:00 to 11:00 AM and 1 more\./.test(await overlay()), await overlay());
  await p.click('#overlay [data-action="save-new-job"]'); await p.waitForTimeout(100);
  check('Save asks first', /Save anyway\?/.test(norm(await h.dialog())));
  await p.click('#overlay .dialog button:not(.bold)'); await p.waitForTimeout(80);
  check('No keeps the form', /New Job/.test(await overlay()));
  await p.click('#overlay [data-action="save-new-job"]'); await p.waitForTimeout(100); await p.click('#overlay .dialog button.bold'); await p.waitForTimeout(150);
  let st = await h.state(); const nj = st.jobs.find(j => j.customerId === 'c6' && j.date === plus(0) && j.time === '10:00');
  check('Save anyway saves 10:00 to 2:00 PM', !!nj && nj.end === '14:00');
  // Assistant: new job with an end time
  h.plan = () => ({ reply: '', actions: [A({ type: 'new_job', customerName: 'Angela Ruiz', phone: '508-555-0126', jobType: 'Junk removal', date: plus(1), time: '09:00', endTime: '12:00', price: '400' })], issues: [] });
  await h.say('Ruiz cleanout tomorrow 9 till noon, 400', 800);
  const rec = norm(h.requests[h.requests.length - 1].records);
  check('records show 9:00 to 11:00 AM for Linda', /Mon, Oct \d+ 9:00 to 11:00 AM · C\d+ Linda Johnson|9:00 to 11:00 AM · C\d+ Linda Johnson/.test(rec), rec.match(/J\d+[^·]*· C\d+ Linda Johnson/) && rec.match(/J\d+[^·]*· C\d+ Linda Johnson/)[0]);
  let o = norm(await h.ov());
  check('Assistant new job shows the end time and the clash', (await p.inputValue('#overlay [data-field="r-end"]')) === '12:00' && /Overlaps Tom & Sue Keane/.test(o), o.slice(0, 400));
  await p.click('#overlay [data-action="assistant-save"]'); await p.waitForTimeout(150);
  const asked = []; for (let i = 0; i < 6 && (await h.hasDialog()); i++) { asked.push(norm(await h.dialog())); await p.click('#overlay .dialog button.bold'); await p.waitForTimeout(350); }
  check('the clash is one of the questions', asked.some(q => /This overlaps Tom & Sue Keane, Junk removal, 8:00 to 11:00 AM( and 1 more)?\. Book it anyway\?/.test(q)), asked.join(' | '));
  st = await h.state(); check('saved 9:00 to 12:00', st.jobs.some(j => j.customerId === 'c5' && j.date === plus(1) && j.time === '09:00' && j.end === '12:00'));
  // Assistant: no end said means no end
  h.plan = () => ({ reply: '', actions: [A({ type: 'new_job', customerName: 'Linda Johnson', phone: '508-555-0147', jobType: 'Estimate', date: plus(5), time: '15:00', price: '0' })], issues: [] });
  await h.say('estimate for Johnson in five days at 3', 800);
  check('no end said: the end switch is off', (await p.locator('#overlay [data-toggle="r-hasEnd"]').getAttribute('aria-checked')) === 'false');
  await p.click('#overlay [data-action="close-sheet"]'); await p.waitForTimeout(80);
  // Assistant: update the end
  h.plan = (note, records) => ({ reply: '', actions: [A({ type: 'update_job', ref: refIn(records, /- (J\d+) [^\n]*Linda Johnson[^\n]*not done/), endTime: '15:00' })], issues: [] });
  await h.say('the Johnson job will run till 3', 800);
  o = norm(await h.ov());
  check('update shows ending 3:00 PM and the clash', /ending 3:00 PM/.test(o) && /Overlaps/.test(o) && (await p.inputValue('#overlay [data-field="u-end"]')) === '15:00', o.slice(0, 400));
  await p.click('#overlay [data-action="assistant-update-save"]'); await p.waitForTimeout(120);
  check('update asks first', /Save anyway\?/.test(norm(await h.dialog())));
  await p.click('#overlay .dialog button.bold'); await p.waitForTimeout(200);
  st = await h.state(); check('the end is saved', st.jobs.find(j => j.id === 'j1').end === '15:00');
  // Book Job with an end time
  h.plan = (note, records) => ({ reply: '', actions: [A({ type: 'update_quote', ref: refIn(records, /- (Q\d+) [^\n]*Dave Macomber/), quoteStatus: 'approved', date: plus(0), time: '16:00', endTime: '18:00' })], issues: [] });
  await h.say('Macomber approved, today 4 to 6', 800);
  o = norm(await h.ov());
  check('Book Job shows the end time; 4 to 6 PM clashes with nothing', /Book Job/.test(o) && (await p.inputValue('#overlay [data-field="g-end"]')) === '18:00' && !/Overlaps/.test(o), o.slice(0, 300));
  await p.click('#overlay [data-action="assistant-g-save"]'); await p.waitForTimeout(250);
  st = await h.state(); const bj = st.jobs.find(j => j.customerId === 'c6' && j.time === '16:00');
  check('books it 4:00 to 6:00 PM without asking', !!bj && bj.end === '18:00' && st.quotes.find(q => q.id === 'q1').status === 'booked');
  await p.click('[data-action="tab"][data-tab="jobs"]'); await p.waitForTimeout(100);
  check('Jobs list shows 4:00 to 6:00 PM', /4:00 to 6:00 PM/.test(await content()));
  await p.click('[data-action="tab"][data-tab="today"]'); await p.waitForTimeout(100);
  await p.screenshot({ path: OUT + 'demo-endtimes.png', clip: await p.locator('#phone').boundingBox() });
  check('no page errors', !h.errors.length, h.errors.join(' | '));
  await h.close(); await done();
  console.log(fails ? fails + ' FAILED' : 'ALL END-TIME CHECKS OK');
})();
